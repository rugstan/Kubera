// Renders the `checklist_templates` seed for the WS-U migration from
// CHECKLIST_TEMPLATES, so the database and the code can never disagree:
// seed.test.ts fails when the block in the migration differs from this output.
// After changing a template, bump TEMPLATE_VERSION and add a new migration
// with the new block (never edit an applied migration).

import { CHECKLIST_PROGRAMS } from "./types";
import { CHECKLIST_TEMPLATES } from "./templates";

export const SEED_BEGIN = "-- BEGIN checklist_templates seed (generated by lib/checklists/seed.ts)";
export const SEED_END = "-- END checklist_templates seed";

export function renderTemplateSeedSql(): string {
  const rows = CHECKLIST_PROGRAMS.map((program) => {
    const t = CHECKLIST_TEMPLATES[program];
    const json = JSON.stringify(t.items);
    if (json.includes("$seed$") || t.title.includes("'")) throw new Error(`Template ${program} cannot be rendered safely`);
    return `  ('${t.program}', '${t.version}', '${t.title}', $seed$${json}$seed$::jsonb)`;
  });
  return [SEED_BEGIN, "insert into public.checklist_templates (program, version, title, items) values", rows.join(",\n"), "on conflict (program, version) do nothing;", SEED_END].join("\n");
}
