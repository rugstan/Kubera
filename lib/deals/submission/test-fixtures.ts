type ObligationSet = "recourse" | "sba" | "hud";
const OWES: Record<ObligationSet, PrincipalRequirement[]> = {
  recourse: ["pfs", "reo_schedule", "credit_authorization", "government_id", "guaranty", "resume"],
  sba: ["pfs", "reo_schedule", "credit_authorization", "government_id", "form_1919", "guaranty", "resume"],
  hud: ["pfs", "reo_schedule", "credit_authorization", "government_id", "hud_2530", "resume"],
};

type Person = { name: string; pct: number; title: string; roles: PrincipalRole[]; pfsUsd: { netWorth: number; liquidity: number } };

function borrowerEntity(pb: number, name: string, formationState = "CA"): SubmissionPrincipal {
  return {
    id: uid(pb, K.principal, 1),
    parentId: null,
    kind: "entity",
    legalName: name,
    roles: ["borrower_entity"],
    title: null,
    ownershipPct: null,
    isGuarantor: false,
    formationState,
    hasPfs: false,
    pfsAsOf: null,
    hasForm1919: false,
    effectivePct: 100,
    hasReoSchedule: false,
    hasHud2530: false,
    hasCreditAuthorization: false,
    owes: [],
  };
}

function individual(pb: number, n: number, parentId: string, p: Person, set: ObligationSet): SubmissionPrincipal {
  const owes = [...OWES[set]];
  return {
    id: uid(pb, K.principal, n),
    parentId,
    kind: "individual",
    legalName: p.name,
    roles: p.roles,
    title: p.title,
    ownershipPct: p.pct,
    isGuarantor: set !== "hud",
    formationState: null,
    hasPfs: true,
    pfsAsOf: PFS_AS_OF,
    hasForm1919: owes.includes("form_1919"),
    effectivePct: p.pct,
    hasReoSchedule: true,
    hasHud2530: owes.includes("hud_2530"),
    hasCreditAuthorization: true,
    owes,
  };
}

