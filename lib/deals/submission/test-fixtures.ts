/** Dollars to cents. */
const usd = (dollars: number) => Math.round(dollars * 100);
const hh = (n: number) => String(n).padStart(2, "0");

/** A valid v4-shaped UUID per (playbook, kind, n) with no long digit runs. */
function uid(pb: number, kind: number, n = 1): string {
  return `5ab${hh(pb)}c${hh(kind)}-0d0e-4f00-8a00-fa${hh(pb)}ce${hh(kind)}be${hh(n)}`;
}
