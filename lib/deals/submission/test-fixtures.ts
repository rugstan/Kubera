// Shared fixtures for the submission module: one complete SubmissionContext
// per playbook and an empty one. Every builder (metrics, requirements,
// readiness, summary, email, tailoring, UI) tests against these.
//
// "Complete" means every Screen and Term sheet item in spec 4.5 can be met:
// sources equal uses, the tranche line equals the loan, PFS on file for every
// guarantor (dated within PFS_MAX_AGE_DAYS of SUBMISSION_FIXTURE_NOW), every
// program section answered. At Underwrite, as on a real file at this point,
// items the lender, a vendor or title supplies (appraisal, Phase I, title,
// closing items) are still requested.
//
// All data is synthetic: invented people, companies and street addresses in
// real cities, example.com mailboxes, CSLB-shaped license numbers and APNs.
// Free text never names a principal (assertEmailSafe checks guarantor names),
// never runs nine digits together, and avoids the copy checkSummaryCopy and
// checkNeutralCopy refuse.
//
// Each call returns fresh objects, so tests may mutate what they get.

